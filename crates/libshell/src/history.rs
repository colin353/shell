//! Shell history with crash-safe append-only log, fuzzy search, and automatic backups.
//!
//! # Design
//!
//! This module uses an append-only log for durability combined with an in-memory
//! index for fast fuzzy search. The key invariant is that we NEVER lose executed
//! commands - when a command is executed, it's immediately written to disk and
//! fsynced before the shell continues.
//!
//! ## Log Format
//!
//! The log is a newline-delimited JSON file where each line is an event:
//! - `exec` events record a new command execution
//! - `amend` events update metadata on a previously recorded command
//!
//! This allows us to record commands immediately on execution, then update
//! with exit codes, duration, etc. when the command completes.
//!
//! ## Concurrency
//!
//! The ShellHistory is designed to be wrapped in `Arc` and shared across
//! multiple shell panes. File-level locking ensures safe concurrent writes.
//!
//! ## Backups
//!
//! Backups are created at exponentially increasing intervals (1h, 2h, 4h, 8h, etc.)
//! to protect against corruption while not using too much disk space.

use fs2::FileExt;
use fuzzy_matcher::skim::SkimMatcherV2;
use fuzzy_matcher::FuzzyMatcher;
use protocol::{HistoryRecord, HistoryScope, HostId, Origin};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fs::{self, File, OpenOptions};
use std::io::{self, BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::sync::{Mutex, RwLock};
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use uuid::Uuid;

/// Unique identifier for a history entry
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct EntryId(String);

impl EntryId {
    pub fn new() -> Self {
        EntryId(Uuid::new_v4().to_string())
    }

    pub fn from_string(s: String) -> Self {
        EntryId(s)
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl Default for EntryId {
    fn default() -> Self {
        Self::new()
    }
}

/// Source of the command - was it typed by a human or generated by AI?
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum CommandSource {
    Human,
    Ai,
}

impl Default for CommandSource {
    fn default() -> Self {
        CommandSource::Human
    }
}

/// A history entry representing an executed command
#[derive(Debug, Clone)]
pub struct HistoryEntry {
    pub id: EntryId,
    pub command: String,
    pub executed_at: SystemTime,
    pub exit_code: Option<i32>,
    pub source: CommandSource,
    pub killed: bool,
    pub duration_ms: Option<u64>,
    /// Working directory when command was executed
    pub cwd: Option<String>,
    /// Where the command executed. `Local` is relative to this log: in any
    /// machine's own history it means "ran here." Mirrored remote entries carry
    /// `Remote(host)`.
    pub origin: Origin,
}

impl HistoryEntry {
    pub fn new(command: String, source: CommandSource) -> Self {
        HistoryEntry {
            id: EntryId::new(),
            command,
            executed_at: SystemTime::now(),
            exit_code: None,
            source,
            killed: false,
            duration_ms: None,
            cwd: None,
            origin: Origin::Local,
        }
    }

    pub fn with_cwd(mut self, cwd: String) -> Self {
        self.cwd = Some(cwd);
        self
    }

    pub fn with_origin(mut self, origin: Origin) -> Self {
        self.origin = origin;
        self
    }
}

/// Whether an origin is the local machine — used to keep local entries' on-disk
/// JSON unchanged (the `origin` field is omitted when `Local`).
fn origin_is_local(origin: &Origin) -> bool {
    matches!(origin, Origin::Local)
}

/// Events that can be written to the append-only log
#[derive(Debug, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "lowercase")]
enum LogEvent {
    /// A new command was executed
    Exec {
        id: String,
        cmd: String,
        #[serde(rename = "time")]
        timestamp: u64,
        source: CommandSource,
        #[serde(skip_serializing_if = "Option::is_none")]
        cwd: Option<String>,
        /// Omitted for local commands; old logs without it default to `Local`.
        #[serde(default, skip_serializing_if = "origin_is_local")]
        origin: Origin,
    },
    /// Amend an existing entry with completion information
    Amend {
        id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        exit_code: Option<i32>,
        #[serde(skip_serializing_if = "Option::is_none")]
        duration_ms: Option<u64>,
        #[serde(skip_serializing_if = "Option::is_none")]
        killed: Option<bool>,
    },
    /// Import from external history (zsh/bash). Always local — imports come from
    /// this machine's shell history files.
    Import {
        id: String,
        cmd: String,
        #[serde(rename = "time")]
        timestamp: u64,
        #[serde(skip_serializing_if = "Option::is_none")]
        original_format: Option<String>,
    },
}

/// Cap on records buffered while no client is attached, so a long-detached
/// daemon doesn't grow without bound. Older records past the cap are dropped
/// (they remain in the remote's own on-disk history regardless).
const MIRROR_OUTBOX_CAP: usize = 2048;

/// Captures completed commands for dual-write up a hop. Installed on the
/// daemon's [`ShellCore`]; the daemon drains it each loop and ships each record
/// to the client as `ServerMsg::HistoryRecorded`, which mirrors it into the
/// local log tagged `Remote(host)`.
///
/// A command is buffered only once it *completes* (so the record carries its
/// exit code), keyed from the metadata captured when it started.
#[derive(Default)]
pub struct HistoryMirror {
    /// In-flight commands by id — command text/cwd/start-time, known at record
    /// time but not at exit time (where only the id is in hand).
    pending: Mutex<HashMap<String, PendingMirror>>,
    /// Completed records awaiting the next drain.
    outbox: Mutex<Vec<HistoryRecord>>,
    /// Set once when the outbox first overflows (so we warn once per episode
    /// rather than per dropped record); cleared on `drain`.
    overflow_warned: std::sync::atomic::AtomicBool,
}

struct PendingMirror {
    command: String,
    cwd: Option<String>,
    executed_at: u64,
}

impl HistoryMirror {
    pub fn new() -> Self {
        Self::default()
    }

    fn now_secs() -> u64 {
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs()
    }

    /// A command started: remember what we'll need to mirror it on completion.
    pub fn on_record(&self, id: &str, command: &str, cwd: Option<String>) {
        self.pending.lock().unwrap().insert(
            id.to_string(),
            PendingMirror {
                command: command.to_string(),
                cwd,
                executed_at: Self::now_secs(),
            },
        );
    }

    /// A command finished (`exit_code = None` means it was killed). Emits the
    /// completed record. The origin is `Local` from the daemon's perspective;
    /// the receiving client rewrites it to `Remote(host)`.
    pub fn on_exit(&self, id: &str, exit_code: Option<i32>) {
        if let Some(p) = self.pending.lock().unwrap().remove(id) {
            use std::sync::atomic::Ordering;
            let mut out = self.outbox.lock().unwrap();
            if out.len() < MIRROR_OUTBOX_CAP {
                out.push(HistoryRecord {
                    id: id.to_string(),
                    command: p.command,
                    executed_at: p.executed_at,
                    exit_code,
                    cwd: p.cwd,
                    origin: Origin::Local,
                });
            } else if !self.overflow_warned.swap(true, Ordering::Relaxed) {
                // Detached long enough to fill the buffer: drop the oldest-past-cap
                // records and warn once. They survive in the remote's own on-disk
                // history, so this only affects local dual-write mirroring.
                eprintln!(
                    "shell: history mirror buffer full ({MIRROR_OUTBOX_CAP}); \
                     dropping mirrored records until a client reattaches"
                );
            }
        }
    }

    /// Take everything buffered so far (for sending to the client).
    pub fn drain(&self) -> Vec<HistoryRecord> {
        self.overflow_warned
            .store(false, std::sync::atomic::Ordering::Relaxed);
        std::mem::take(&mut *self.outbox.lock().unwrap())
    }
}

/// Search result from fuzzy matching
#[derive(Debug, Clone)]
pub struct SearchResult {
    pub entry: HistoryEntry,
    pub score: i64,
}

/// Breakdown of the scoring components for a search result
#[derive(Debug, Clone, Default)]
pub struct ScoreBreakdown {
    /// Score from the fuzzy matcher (normalized)
    pub match_score: i64,
    /// Bonus for match density (matched chars / command length)
    pub density_bonus: i64,
    /// Bonus for successful exit code (0)
    pub exit_code_bonus: i64,
    /// Bonus based on how many times this command has been run
    pub frequency_bonus: i64,
    /// Bonus based on how recently the command was last run
    pub recency_bonus: i64,
    /// Penalty (subtracted) for entries whose origin differs from the preferred
    /// host under [`HistoryScope::Prefer`]. Zero otherwise.
    pub off_host_penalty: i64,
}

impl ScoreBreakdown {
    /// Calculate the total score from all components
    pub fn total(&self) -> i64 {
        self.match_score
            + self.density_bonus
            + self.exit_code_bonus
            + self.frequency_bonus
            + self.recency_bonus
            - self.off_host_penalty
    }
}

/// Off-host penalty magnitude for [`HistoryScope::Prefer`]. Sized to sit below
/// the frequency bonus (max 100) — a command you run constantly everywhere
/// still surfaces — but above the recency bonus (max 20), so all else equal an
/// on-host command wins.
const OFF_HOST_PENALTY: i64 = 60;

/// Whether `scope` admits an entry with the given origin at all.
fn scope_includes(scope: &HistoryScope, origin: &Origin) -> bool {
    match scope {
        HistoryScope::Only(target) => origin == target,
        HistoryScope::All | HistoryScope::Prefer(_) => true,
    }
}

/// Score penalty applied to an entry's origin under `scope`.
fn scope_penalty(scope: &HistoryScope, origin: &Origin) -> i64 {
    match scope {
        HistoryScope::Prefer(target) if origin != target => OFF_HOST_PENALTY,
        _ => 0,
    }
}

/// Search result with match indices for highlighting
#[derive(Debug, Clone)]
pub struct HistorySearchResult {
    pub entry: HistoryEntry,
    /// Total computed score (for sorting)
    pub score: i64,
    /// Breakdown of individual score components
    pub score_breakdown: ScoreBreakdown,
    /// Character indices that matched the query (for highlighting)
    pub match_indices: Vec<usize>,
}

/// Backup interval configuration
#[derive(Debug, Clone)]
pub struct BackupConfig {
    /// Base intervals for backups (in seconds)
    /// Default: 1h, 2h, 4h, 8h, 16h, 1d, 2d, 4d, 1w, 2w, 1mo
    pub intervals: Vec<Duration>,
}

impl Default for BackupConfig {
    fn default() -> Self {
        BackupConfig {
            intervals: vec![
                Duration::from_secs(3600),    // 1 hour
                Duration::from_secs(7200),    // 2 hours
                Duration::from_secs(14400),   // 4 hours
                Duration::from_secs(28800),   // 8 hours
                Duration::from_secs(57600),   // 16 hours
                Duration::from_secs(86400),   // 1 day
                Duration::from_secs(172800),  // 2 days
                Duration::from_secs(345600),  // 4 days
                Duration::from_secs(604800),  // 1 week
                Duration::from_secs(1209600), // 2 weeks
                Duration::from_secs(2592000), // ~1 month
            ],
        }
    }
}

/// Shell history manager
///
/// This is designed to be wrapped in `Arc` for concurrent access from
/// multiple shell panes.
pub struct ShellHistory {
    /// In-memory entries indexed by ID
    entries: RwLock<HashMap<EntryId, HistoryEntry>>,

    /// Ordered list of entry IDs (most recent last)
    entry_order: RwLock<Vec<EntryId>>,

    /// Path to the history log file
    log_path: PathBuf,

    /// Lock for serializing writes
    write_lock: Mutex<()>,

    /// Fuzzy matcher for search
    matcher: SkimMatcherV2,

    /// Backup configuration
    backup_config: BackupConfig,

    /// Last backup times for each interval
    last_backups: RwLock<Vec<Option<SystemTime>>>,
}

impl ShellHistory {
    /// Create a new ShellHistory, loading from the specified log file if it exists
    pub fn new(log_path: impl AsRef<Path>) -> io::Result<Self> {
        let log_path = log_path.as_ref().to_path_buf();
        let backup_config = BackupConfig::default();
        let last_backups = RwLock::new(vec![None; backup_config.intervals.len()]);

        let history = ShellHistory {
            entries: RwLock::new(HashMap::new()),
            entry_order: RwLock::new(Vec::new()),
            log_path,
            write_lock: Mutex::new(()),
            matcher: SkimMatcherV2::default(),
            backup_config,
            last_backups,
        };

        // Load existing history if the file exists
        if history.log_path.exists() {
            history.load_log()?;
        }

        Ok(history)
    }

    /// Create a new ShellHistory with custom backup configuration
    pub fn with_backup_config(
        log_path: impl AsRef<Path>,
        backup_config: BackupConfig,
    ) -> io::Result<Self> {
        let log_path = log_path.as_ref().to_path_buf();
        let last_backups = RwLock::new(vec![None; backup_config.intervals.len()]);

        let history = ShellHistory {
            entries: RwLock::new(HashMap::new()),
            entry_order: RwLock::new(Vec::new()),
            log_path,
            write_lock: Mutex::new(()),
            matcher: SkimMatcherV2::default(),
            backup_config,
            last_backups,
        };

        if history.log_path.exists() {
            history.load_log()?;
        }

        Ok(history)
    }

    /// Load the log file and rebuild in-memory state
    fn load_log(&self) -> io::Result<()> {
        let file = File::open(&self.log_path)?;
        let reader = BufReader::new(file);

        let mut entries = self.entries.write().unwrap();
        let mut entry_order = self.entry_order.write().unwrap();

        for line in reader.lines() {
            let line = line?;
            let trimmed = line.trim();
            if trimmed.is_empty() {
                continue;
            }

            // Skip lines that don't look like JSON objects
            if !trimmed.starts_with('{') {
                eprintln!(
                    "Warning: skipping non-JSON history line: {}",
                    if trimmed.len() > 50 {
                        &trimmed[..50]
                    } else {
                        trimmed
                    }
                );
                continue;
            }

            match serde_json::from_str::<LogEvent>(&line) {
                Ok(event) => self.apply_event(&mut entries, &mut entry_order, event),
                Err(e) => {
                    // Log parse errors but continue - we don't want to lose history
                    // due to a single corrupt line
                    eprintln!("Warning: failed to parse history line: {}", e);
                }
            }
        }

        Ok(())
    }

    /// Apply a log event to the in-memory state
    fn apply_event(
        &self,
        entries: &mut HashMap<EntryId, HistoryEntry>,
        entry_order: &mut Vec<EntryId>,
        event: LogEvent,
    ) {
        match event {
            LogEvent::Exec {
                id,
                cmd,
                timestamp,
                source,
                cwd,
                origin,
            } => {
                let entry_id = EntryId::from_string(id);
                let entry = HistoryEntry {
                    id: entry_id.clone(),
                    command: cmd,
                    executed_at: UNIX_EPOCH + Duration::from_secs(timestamp),
                    exit_code: None,
                    source,
                    killed: false,
                    duration_ms: None,
                    cwd,
                    origin,
                };
                entries.insert(entry_id.clone(), entry);
                entry_order.push(entry_id);
            }
            LogEvent::Amend {
                id,
                exit_code,
                duration_ms,
                killed,
            } => {
                let entry_id = EntryId::from_string(id);
                if let Some(entry) = entries.get_mut(&entry_id) {
                    if let Some(code) = exit_code {
                        entry.exit_code = Some(code);
                    }
                    if let Some(dur) = duration_ms {
                        entry.duration_ms = Some(dur);
                    }
                    if let Some(k) = killed {
                        entry.killed = k;
                    }
                }
            }
            LogEvent::Import {
                id, cmd, timestamp, ..
            } => {
                let entry_id = EntryId::from_string(id);
                let entry = HistoryEntry {
                    id: entry_id.clone(),
                    command: cmd,
                    executed_at: UNIX_EPOCH + Duration::from_secs(timestamp),
                    exit_code: None,
                    source: CommandSource::Human,
                    killed: false,
                    duration_ms: None,
                    cwd: None,
                    origin: Origin::Local,
                };
                entries.insert(entry_id.clone(), entry);
                entry_order.push(entry_id);
            }
        }
    }

    /// Write an event to the log file with fsync for durability
    fn write_event(&self, event: &LogEvent) -> io::Result<()> {
        let _lock = self.write_lock.lock().unwrap();

        // Ensure parent directory exists
        if let Some(parent) = self.log_path.parent() {
            fs::create_dir_all(parent)?;
        }

        let mut file = OpenOptions::new()
            .create(true)
            .append(true)
            .open(&self.log_path)?;

        // Use file locking for safe concurrent access across processes
        file.lock_exclusive()?;

        let mut line = serde_json::to_string(event)?;
        line.push('\n');
        file.write_all(line.as_bytes())?;
        file.sync_all()?;

        file.unlock()?;

        Ok(())
    }

    /// Record a new command execution
    ///
    /// This immediately writes to the log and fsyncs before returning,
    /// ensuring the command is never lost even if the shell crashes.
    ///
    /// Returns the EntryId which can be used to amend the entry later.
    pub fn record_command(&self, command: String, source: CommandSource) -> io::Result<EntryId> {
        self.record_command_with_cwd(command, source, None)
    }

    /// Record a new command execution with working directory.
    ///
    /// Origin defaults to [`Origin::Local`]; use
    /// [`record_command_with_origin`](Self::record_command_with_origin) to tag a
    /// command that ran on a remote host.
    pub fn record_command_with_cwd(
        &self,
        command: String,
        source: CommandSource,
        cwd: Option<String>,
    ) -> io::Result<EntryId> {
        self.record_command_with_origin(command, source, cwd, Origin::Local)
    }

    /// Record a new command execution, tagging where it ran.
    pub fn record_command_with_origin(
        &self,
        command: String,
        source: CommandSource,
        cwd: Option<String>,
        origin: Origin,
    ) -> io::Result<EntryId> {
        let entry = HistoryEntry {
            id: EntryId::new(),
            command: command.clone(),
            executed_at: SystemTime::now(),
            exit_code: None,
            source,
            killed: false,
            duration_ms: None,
            cwd: cwd.clone(),
            origin: origin.clone(),
        };

        let timestamp = entry
            .executed_at
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_secs();

        let event = LogEvent::Exec {
            id: entry.id.0.clone(),
            cmd: command,
            timestamp,
            source,
            cwd,
            origin,
        };

        // Write to disk first (crash-safe)
        self.write_event(&event)?;

        // Then update in-memory state
        let entry_id = entry.id.clone();
        {
            let mut entries = self.entries.write().unwrap();
            let mut order = self.entry_order.write().unwrap();
            entries.insert(entry_id.clone(), entry);
            order.push(entry_id.clone());
        }

        // Check if we need to create a backup
        self.maybe_backup()?;

        Ok(entry_id)
    }

    /// Mirror a command that ran on another host into this log, tagged
    /// `Remote(host)`. Idempotent: a resync/replay that resends the same entry
    /// (keyed by the remote's id) is ignored, so the local log never doubles up.
    pub fn record_mirrored(&self, record: &HistoryRecord, host: &HostId) -> io::Result<()> {
        let id = EntryId::from_string(record.id.clone());
        if self.entries.read().unwrap().contains_key(&id) {
            return Ok(());
        }

        let origin = Origin::Remote(host.clone());
        let entry = HistoryEntry {
            id: id.clone(),
            command: record.command.clone(),
            executed_at: UNIX_EPOCH + Duration::from_secs(record.executed_at),
            exit_code: record.exit_code,
            source: CommandSource::Human,
            killed: false,
            duration_ms: None,
            cwd: record.cwd.clone(),
            origin: origin.clone(),
        };

        // Persist (crash-safe) the original execution, then its completion.
        self.write_event(&LogEvent::Exec {
            id: record.id.clone(),
            cmd: record.command.clone(),
            timestamp: record.executed_at,
            source: CommandSource::Human,
            cwd: record.cwd.clone(),
            origin,
        })?;
        if let Some(code) = record.exit_code {
            self.write_event(&LogEvent::Amend {
                id: record.id.clone(),
                exit_code: Some(code),
                duration_ms: None,
                killed: Some(false),
            })?;
        }

        {
            let mut entries = self.entries.write().unwrap();
            let mut order = self.entry_order.write().unwrap();
            entries.insert(id.clone(), entry);
            order.push(id);
        }
        Ok(())
    }

    /// Amend an existing history entry with completion information
    pub fn amend_entry(
        &self,
        id: &EntryId,
        exit_code: Option<i32>,
        duration_ms: Option<u64>,
        killed: Option<bool>,
    ) -> io::Result<()> {
        let event = LogEvent::Amend {
            id: id.0.clone(),
            exit_code,
            duration_ms,
            killed,
        };

        // Write to disk first
        self.write_event(&event)?;

        // Then update in-memory state
        let mut entries = self.entries.write().unwrap();
        if let Some(entry) = entries.get_mut(id) {
            if let Some(code) = exit_code {
                entry.exit_code = Some(code);
            }
            if let Some(dur) = duration_ms {
                entry.duration_ms = Some(dur);
            }
            if let Some(k) = killed {
                entry.killed = k;
            }
        }

        Ok(())
    }

    /// Mark a command as killed (e.g., by Ctrl+C)
    pub fn mark_killed(&self, id: &EntryId) -> io::Result<()> {
        self.amend_entry(id, None, None, Some(true))
    }

    /// Record the exit code of a command
    pub fn record_exit(&self, id: &EntryId, exit_code: i32, duration_ms: u64) -> io::Result<()> {
        self.amend_entry(id, Some(exit_code), Some(duration_ms), Some(false))
    }

    /// Get the total number of history entries
    pub fn len(&self) -> usize {
        self.entries.read().unwrap().len()
    }

    /// Check if history is empty
    pub fn is_empty(&self) -> bool {
        self.entries.read().unwrap().is_empty()
    }

    /// Get a specific entry by ID
    pub fn get(&self, id: &EntryId) -> Option<HistoryEntry> {
        self.entries.read().unwrap().get(id).cloned()
    }

    /// Get the most recent N entries
    pub fn recent(&self, n: usize) -> Vec<HistoryEntry> {
        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        order
            .iter()
            .rev()
            .take(n)
            .filter_map(|id| entries.get(id).cloned())
            .collect()
    }

    /// Get all entries in chronological order
    pub fn all_entries(&self) -> Vec<HistoryEntry> {
        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        order
            .iter()
            .filter_map(|id| entries.get(id).cloned())
            .collect()
    }

    /// Fuzzy search through history
    ///
    /// Returns matching entries sorted by match score (best matches first)
    pub fn search(&self, query: &str) -> Vec<SearchResult> {
        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        let mut results: Vec<SearchResult> = order
            .iter()
            .filter_map(|id| {
                let entry = entries.get(id)?;
                let score = self.matcher.fuzzy_match(&entry.command, query)?;
                Some(SearchResult {
                    entry: entry.clone(),
                    score,
                })
            })
            .collect();

        // Sort by score descending
        results.sort_by(|a, b| b.score.cmp(&a.score));

        results
    }

    /// Search with a maximum number of results
    pub fn search_limit(&self, query: &str, limit: usize) -> Vec<SearchResult> {
        let mut results = self.search(query);
        results.truncate(limit);
        results
    }

    /// Search for exact prefix matches (useful for tab completion)
    pub fn search_prefix(&self, prefix: &str) -> Vec<HistoryEntry> {
        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        order
            .iter()
            .rev()
            .filter_map(|id| {
                let entry = entries.get(id)?;
                if entry.command.starts_with(prefix) {
                    Some(entry.clone())
                } else {
                    None
                }
            })
            .collect()
    }

    /// Search history with match indices for highlighting.
    ///
    /// This method performs fuzzy search and returns results with:
    /// - Match indices for highlighting matched characters
    /// - Enhanced scoring that combines multiple factors:
    ///   - **Frequency bonus** (most important): Commands run many times score higher
    ///   - **Match score**: Quality of the fuzzy match (normalized)
    ///   - **Exit code bonus**: Successful commands (exit_code = 0) score higher
    ///   - **Recency bonus**: More recently executed commands score higher
    ///
    /// Results are deduplicated by command text, keeping the most recent entry
    /// for each unique command (which also has the best recency).
    ///
    /// If query is empty, returns most recent unique commands.
    pub fn search_with_indices(&self, query: &str, limit: usize) -> Vec<HistorySearchResult> {
        self.search_with_indices_scoped(query, limit, &HistoryScope::All)
    }

    /// Like [`search_with_indices`](Self::search_with_indices), but weights
    /// results by origin: `Only` filters to a single host, `Prefer` downranks
    /// off-host entries (see [`OFF_HOST_PENALTY`]), and `All` is unweighted.
    pub fn search_with_indices_scoped(
        &self,
        query: &str,
        limit: usize,
        scope: &HistoryScope,
    ) -> Vec<HistorySearchResult> {
        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        // Scoring weights:
        // - Frequency is most important (commands you run often are likely what you want)
        // - Match quality + density together determine how well the query fits
        // - Recency is a tiebreaker (prefer recently used commands)
        // - Exit code is a minor bonus (success is nice but shouldn't override match quality)
        const MAX_FREQUENCY_BONUS: i64 = 100; // Dominates other factors
        const MAX_MATCH_SCORE: i64 = 50; // Fuzzy match quality
        const MAX_DENSITY_BONUS: i64 = 40; // Reward concentrated matches (query_len / cmd_len)
        const MAX_RECENCY_BONUS: i64 = 20; // Mild recency preference
        const MAX_EXIT_CODE_BONUS: i64 = 10; // Minor tiebreaker for successful commands

        let query_len = query.chars().count();

        // Pre-compute command statistics: (execution_count, most_recent_index, had_success)
        struct CommandStats {
            count: usize,
            most_recent_idx: usize,
            had_success: bool,
        }
        let mut command_stats: HashMap<&str, CommandStats> = HashMap::new();
        let mut max_count: usize = 1;

        for (idx, id) in order.iter().enumerate() {
            if let Some(entry) = entries.get(id) {
                if !scope_includes(scope, &entry.origin) {
                    continue;
                }
                let stats = command_stats.entry(&entry.command).or_insert(CommandStats {
                    count: 0,
                    most_recent_idx: idx,
                    had_success: false,
                });
                stats.count += 1;
                stats.most_recent_idx = idx; // Last one wins (order is chronological)
                if entry.exit_code == Some(0) {
                    stats.had_success = true;
                }
                max_count = max_count.max(stats.count);
            }
        }

        let total_entries = order.len();

        if query.is_empty() {
            // Return most recent unique commands when query is empty
            // Still apply scoring for frequency and exit code
            let mut seen_commands = std::collections::HashSet::new();
            let mut results = Vec::new();
            for id in order.iter().rev() {
                if let Some(entry) = entries.get(id) {
                    if !scope_includes(scope, &entry.origin) {
                        continue;
                    }
                    if seen_commands.insert(entry.command.clone()) {
                        let stats = command_stats.get(entry.command.as_str());
                        let mut breakdown = ScoreBreakdown::default();

                        if let Some(stats) = stats {
                            // Frequency bonus (log scale to avoid extreme dominance)
                            let freq_factor =
                                (stats.count as f64).ln_1p() / (max_count as f64).ln_1p();
                            breakdown.frequency_bonus =
                                (freq_factor * MAX_FREQUENCY_BONUS as f64) as i64;

                            // Exit code bonus
                            if stats.had_success {
                                breakdown.exit_code_bonus = MAX_EXIT_CODE_BONUS;
                            }
                        }

                        breakdown.off_host_penalty = scope_penalty(scope, &entry.origin);
                        let score = breakdown.total();
                        results.push(HistorySearchResult {
                            entry: entry.clone(),
                            score,
                            score_breakdown: breakdown,
                            match_indices: Vec::new(),
                        });
                        if results.len() >= limit {
                            break;
                        }
                    }
                }
            }
            return results;
        }

        // Find the max fuzzy score for normalization
        let mut max_fuzzy_score: i64 = 1;
        let matches: Vec<_> = order
            .iter()
            .filter_map(|id| {
                let entry = entries.get(id)?;
                if !scope_includes(scope, &entry.origin) {
                    return None;
                }
                let (score, indices) = self.matcher.fuzzy_indices(&entry.command, query)?;
                Some((id, entry, score, indices))
            })
            .collect();

        for (_, _, score, _) in &matches {
            max_fuzzy_score = max_fuzzy_score.max(*score);
        }

        // Build results with composite scoring
        let mut results: Vec<HistorySearchResult> = matches
            .into_iter()
            .filter_map(|(_, entry, fuzzy_score, indices)| {
                let stats = command_stats.get(entry.command.as_str())?;

                let mut breakdown = ScoreBreakdown::default();

                // Match score (normalized to MAX_MATCH_SCORE)
                let match_factor = fuzzy_score as f64 / max_fuzzy_score as f64;
                breakdown.match_score = (match_factor * MAX_MATCH_SCORE as f64) as i64;

                // Density bonus: query_len / command_len
                // A 7-char query matching a 10-char command = 0.7 density (high)
                // A 7-char query matching a 100-char command = 0.07 density (low)
                let cmd_len = entry.command.chars().count().max(1);
                let density = query_len as f64 / cmd_len as f64;
                // Clamp to 1.0 (in case query is longer than command, though unlikely)
                let density = density.min(1.0);
                breakdown.density_bonus = (density * MAX_DENSITY_BONUS as f64) as i64;

                // Frequency bonus (log scale to smooth out extreme counts)
                let freq_factor = (stats.count as f64).ln_1p() / (max_count as f64).ln_1p();
                breakdown.frequency_bonus = (freq_factor * MAX_FREQUENCY_BONUS as f64) as i64;

                // Exit code bonus (if this command ever succeeded)
                if stats.had_success {
                    breakdown.exit_code_bonus = MAX_EXIT_CODE_BONUS;
                }

                // Recency bonus (based on most recent execution of this command)
                if total_entries > 1 {
                    let recency_factor = stats.most_recent_idx as f64 / (total_entries - 1) as f64;
                    breakdown.recency_bonus = (recency_factor * MAX_RECENCY_BONUS as f64) as i64;
                }

                // Origin weighting (downrank off-host entries under `Prefer`).
                breakdown.off_host_penalty = scope_penalty(scope, &entry.origin);

                let score = breakdown.total();
                Some(HistorySearchResult {
                    entry: entry.clone(),
                    score,
                    score_breakdown: breakdown,
                    match_indices: indices,
                })
            })
            .collect();

        // Sort by score descending
        results.sort_by(|a, b| b.score.cmp(&a.score));

        // Deduplicate by command text, keeping highest-scoring entry for each command
        let mut seen_commands = std::collections::HashSet::new();
        results.retain(|result| seen_commands.insert(result.entry.command.clone()));

        // Truncate to limit
        results.truncate(limit);

        results
    }

    /// Import from a .zsh_history file
    ///
    /// Format: `: timestamp:0;command` or just `command` for older formats
    pub fn import_zsh_history(&self, path: impl AsRef<Path>) -> io::Result<usize> {
        let file = File::open(path)?;
        let reader = BufReader::new(file);
        let mut count = 0;

        for line in reader.lines() {
            let line = line?;
            let (timestamp, command) = parse_zsh_history_line(&line);

            if command.is_empty() {
                continue;
            }

            // Check for duplicates
            {
                let entries = self.entries.read().unwrap();
                if entries.values().any(|e| e.command == command) {
                    continue;
                }
            }

            let id = EntryId::new();
            let event = LogEvent::Import {
                id: id.0.clone(),
                cmd: command.clone(),
                timestamp,
                original_format: Some("zsh".to_string()),
            };

            self.write_event(&event)?;

            let entry = HistoryEntry {
                id: id.clone(),
                command,
                executed_at: UNIX_EPOCH + Duration::from_secs(timestamp),
                exit_code: None,
                source: CommandSource::Human,
                killed: false,
                duration_ms: None,
                cwd: None,
                origin: Origin::Local,
            };

            let mut entries = self.entries.write().unwrap();
            let mut order = self.entry_order.write().unwrap();
            entries.insert(id.clone(), entry);
            order.push(id);

            count += 1;
        }

        Ok(count)
    }

    /// Import from a .bash_history file
    ///
    /// Format: One command per line, or with timestamps if HISTTIMEFORMAT is set
    pub fn import_bash_history(&self, path: impl AsRef<Path>) -> io::Result<usize> {
        let file = File::open(path)?;
        let reader = BufReader::new(file);
        let mut count = 0;
        let mut pending_timestamp: Option<u64> = None;

        for line in reader.lines() {
            let line = line?;

            // Check for timestamp line (format: #1234567890)
            if line.starts_with('#') {
                if let Ok(ts) = line[1..].trim().parse::<u64>() {
                    pending_timestamp = Some(ts);
                    continue;
                }
            }

            let command = line.trim().to_string();
            if command.is_empty() || command.starts_with('#') {
                continue;
            }

            // Check for duplicates
            {
                let entries = self.entries.read().unwrap();
                if entries.values().any(|e| e.command == command) {
                    pending_timestamp = None;
                    continue;
                }
            }

            let timestamp = pending_timestamp.unwrap_or_else(|| {
                SystemTime::now()
                    .duration_since(UNIX_EPOCH)
                    .unwrap_or_default()
                    .as_secs()
            });
            pending_timestamp = None;

            let id = EntryId::new();
            let event = LogEvent::Import {
                id: id.0.clone(),
                cmd: command.clone(),
                timestamp,
                original_format: Some("bash".to_string()),
            };

            self.write_event(&event)?;

            let entry = HistoryEntry {
                id: id.clone(),
                command,
                executed_at: UNIX_EPOCH + Duration::from_secs(timestamp),
                exit_code: None,
                source: CommandSource::Human,
                killed: false,
                duration_ms: None,
                cwd: None,
                origin: Origin::Local,
            };

            let mut entries = self.entries.write().unwrap();
            let mut order = self.entry_order.write().unwrap();
            entries.insert(id.clone(), entry);
            order.push(id);

            count += 1;
        }

        Ok(count)
    }

    /// Check if a backup is needed and create one if so
    fn maybe_backup(&self) -> io::Result<()> {
        let now = SystemTime::now();
        let mut last_backups = self.last_backups.write().unwrap();

        for (i, interval) in self.backup_config.intervals.iter().enumerate() {
            let needs_backup = match last_backups[i] {
                None => true,
                Some(last) => now.duration_since(last).unwrap_or_default() >= *interval,
            };

            if needs_backup {
                self.create_backup(i)?;
                last_backups[i] = Some(now);
            }
        }

        Ok(())
    }

    /// Create a backup at the specified interval index
    fn create_backup(&self, interval_index: usize) -> io::Result<()> {
        if !self.log_path.exists() {
            return Ok(());
        }

        // A path with no file name (e.g. "/" or "..") has nothing sensible to
        // back up; skip rather than panic. Backups are best-effort.
        let Some(file_name) = self.log_path.file_name() else {
            return Ok(());
        };
        let backup_name = format!("{}.backup.{}", file_name.to_string_lossy(), interval_index);
        let backup_path = match self.log_path.parent() {
            Some(parent) => parent.join(backup_name),
            None => PathBuf::from(backup_name),
        };

        fs::copy(&self.log_path, &backup_path)?;

        Ok(())
    }

    /// Force a backup at all intervals (useful before shutdown)
    pub fn force_backup(&self) -> io::Result<()> {
        for i in 0..self.backup_config.intervals.len() {
            self.create_backup(i)?;
        }
        Ok(())
    }

    /// Get the path to the log file
    pub fn log_path(&self) -> &Path {
        &self.log_path
    }

    /// Compact the log file by rewriting it with only the current state
    ///
    /// This removes redundant amend entries and reduces file size.
    /// Call this periodically (e.g., on shell startup) if the log gets large.
    pub fn compact(&self) -> io::Result<()> {
        let _lock = self.write_lock.lock().unwrap();

        // Create backup before compacting
        self.force_backup()?;

        let entries = self.entries.read().unwrap();
        let order = self.entry_order.read().unwrap();

        // Write to a temp file first
        let temp_path = self.log_path.with_extension("log.tmp");
        {
            let mut file = OpenOptions::new()
                .create(true)
                .write(true)
                .truncate(true)
                .open(&temp_path)?;

            for id in order.iter() {
                if let Some(entry) = entries.get(id) {
                    // Write as a single exec event with all data
                    let timestamp = entry
                        .executed_at
                        .duration_since(UNIX_EPOCH)
                        .unwrap_or_default()
                        .as_secs();

                    let exec_event = LogEvent::Exec {
                        id: entry.id.0.clone(),
                        cmd: entry.command.clone(),
                        timestamp,
                        source: entry.source,
                        cwd: entry.cwd.clone(),
                        origin: entry.origin.clone(),
                    };

                    let mut line = serde_json::to_string(&exec_event)?;
                    line.push('\n');
                    file.write_all(line.as_bytes())?;

                    // Write amend if there's completion data
                    if entry.exit_code.is_some() || entry.duration_ms.is_some() || entry.killed {
                        let amend_event = LogEvent::Amend {
                            id: entry.id.0.clone(),
                            exit_code: entry.exit_code,
                            duration_ms: entry.duration_ms,
                            killed: if entry.killed { Some(true) } else { None },
                        };
                        let mut line = serde_json::to_string(&amend_event)?;
                        line.push('\n');
                        file.write_all(line.as_bytes())?;
                    }
                }
            }

            file.sync_all()?;
        }

        // Atomically replace the old file
        fs::rename(&temp_path, &self.log_path)?;

        Ok(())
    }
}

/// Parse a zsh_history line
///
/// Format: `: timestamp:0;command` or just `command`
fn parse_zsh_history_line(line: &str) -> (u64, String) {
    // Extended format: `: 1234567890:0;command`
    if line.starts_with(": ") {
        if let Some(semi_pos) = line.find(';') {
            let meta = &line[2..semi_pos];
            let command = line[semi_pos + 1..].to_string();

            // Parse timestamp from "timestamp:0" format
            if let Some(colon_pos) = meta.find(':') {
                if let Ok(ts) = meta[..colon_pos].parse::<u64>() {
                    return (ts, command);
                }
            }
        }
    }

    // Simple format: just the command
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    (now, line.to_string())
}

